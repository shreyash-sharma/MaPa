import csv
import os
from datetime import datetime, timezone
from pathlib import Path

from mapa_syn.paths import data_root
from mapa_syn.io import write_json, read_json, sha256

SEED = 20261101
ROOT = data_root() / 'mapa-rhythm-release'
CLAIM = 'Derived timelines are generated by models fitted to real phone logs. Every disruption is injected.'


def candidate_dir(version='v1'):
    return ROOT/('candidate' if version=='v1' else 'candidate-'+version)


def trial(stage, trial_id, status, details):
    path = data_root() / 'logs/trials.csv'
    path.parent.mkdir(parents=True, exist_ok=True)
    exists = path.exists()
    with path.open('a', newline='', encoding='utf-8') as stream:
        writer = csv.writer(stream)
        if not exists:
            writer.writerow(['timestamp_utc', 'stage', 'trial_id', 'status', 'details'])
        writer.writerow([datetime.now(timezone.utc).isoformat(), stage, trial_id, status, details])


def progress(message):
    path = data_root() / 'logs/build-status.md'
    if (ROOT/'release-checks.json').exists():
        checks=read_json(ROOT/'release-checks.json')
        pending=[f'C{i}' for i in range(1,9) if not checks.get(f'C{i}',False)]
        banner='> MaPa-Rhythm release: '+('INCOMPLETE; pending '+', '.join(pending) if pending else 'artifact checks PASS; completion audit still required')+'. final/ remains frozen; no upload or email.\n\n'
        # Older build logs may contain bytes written under the Windows codepage.
        # Preserve readable text while normalizing them on the next progress write.
        text=path.read_text(encoding='utf-8',errors='replace')
        if text.startswith('> MaPa-Rhythm release:'):text=text.split('\n\n',1)[1]
        path.write_text(banner+text,encoding='utf-8')
    with path.open('a', encoding='utf-8') as stream:
        stream.write('\n\n### MaPa-Rhythm release progress — ' + datetime.now(timezone.utc).isoformat() + '\n\n' + message + '\n')


def freeze_protocol():
    ROOT.mkdir(parents=True, exist_ok=True)
    target = ROOT / 'protocol.json'
    if target.exists():
        return read_json(target)
    from mapa_syn.generator.data import directory
    roles = read_json(directory() / 'roles-v013.json')
    remap = {'fit': 'train', 'tune': 'val', 'fidelity_test': 'test'}
    people = [dict(p, split=remap[p['partition']]) for p in roles['people'] if p['partition'] in remap]
    assert not set(p['pid'] for p in people) & set(roles['reserved_real_check'])
    protocol = dict(seed=SEED, people=people, reserved_real_check=roles['reserved_real_check'],
                    derived_splits={'train': list(range(140)), 'val': list(range(140, 170)), 'test': list(range(170, 200))},
                    source_roles_sha256=sha256(directory() / 'roles-v013.json'),
                    historical_exposure=roles['historical_exposure'],
                    requirements='User release objective supersedes S2b review gate and four-candidate stop; no upload.',
                    deadline='2026-11-03T12:00:00-05:00',
                    evaluation='Tune detector settings on validation only; do not change test people, seeds, scenarios or labels after evaluation.',
                    data_optimization='Quiet tail, hourly profile, daily counts and cited age aggregates only; never detector scores.')
    write_json(target, protocol)
    trial('protocol', 'release-v1', 'FROZEN', 'Person splits, reserved pids, seeds and evaluation policy frozen')
    return protocol
