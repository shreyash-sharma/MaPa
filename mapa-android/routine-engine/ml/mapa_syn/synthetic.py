"""Prepare fresh synthetic base timelines without any injected episodes."""
from .bins import FIELDS, validate_rows
from .io import read_csv, sha256, write_csv, write_json
from .paths import ENGINE, data_root, version_root


def prepare(parents=200, days=120, seed=20261031):
    if parents < 1 or days < 28:
        raise ValueError("Synthetic base requires positive population and at least 28 days")
    from mapa_rhythm.synth import generate
    sims = generate(parents, days, seed, "syn-v01-", with_events=False)
    if any(sim.episodes for sim in sims):
        raise RuntimeError("Base generator returned injected episodes; refusing to continue")
    out = data_root() / "converted" / "synthetic"

    def rows():
        for sim in sims:
            for t in range(sim.days * 96):
                observed = int(sim.interactions[t]) >= 0 and bool(sim.usage_ok[t]) and bool(sim.phone_on[t])
                yield dict(pid=sim.pid, t=t, interactions=int(sim.interactions[t]) if observed else -1,
                           phone_on=int(sim.phone_on[t]), usage_ok=int(sim.usage_ok[t]), network_ok=int(sim.network_ok[t]),
                           charging=int(sim.charging[t]), battery=int(sim.battery[t]), paused=int(sim.paused[t]),
                           moved=-1, present=int(sim.phone_on[t]), coverage_min=15 if observed else 0,
                           observation_basis="synthetic")

    write_csv(out / "bins.csv.gz", rows(), FIELDS)
    validate_rows(read_csv(out / "bins.csv.gz"))
    meta = [dict(pid=s.pid, start_dow=s.start_dow, days=s.days,
                 observed_days=sum(any(int(s.interactions[d * 96 + b]) >= 0 and bool(s.phone_on[d * 96 + b])
                                       and bool(s.usage_ok[d * 96 + b]) for b in range(96)) for d in range(days))) for s in sims]
    write_csv(out / "parents.csv", meta, ["pid", "start_dow", "days", "observed_days"])
    write_csv(out / "people.csv", [dict(pid=s.pid, source="synthetic", age_group="unknown") for s in sims], ["pid", "source", "age_group"])
    summary = dict(source="synthetic", parents=parents, days=days, bins=parents * days * 96, seed=seed,
                   with_events=False, actual_episodes_generated=0, observation_basis="synthetic",
                   generator="mapa_rhythm.synth.generate", generator_sha256=sha256(ENGINE / "ml/mapa_rhythm/synth.py"),
                   bins_sha256=sha256(out / "bins.csv.gz"), status="WAITING_FOR_REVIEW_BEFORE_INJECTION")
    write_json(out / "summary.json", summary)
    (out / "README.md").write_text("# Synthetic base parents\n\n"
        "Generated by the existing, unchanged rhythm harness generator API with a new seed and with_events=False. "
        "No original harness dataset was overwritten and no episodes were injected. Population size, duration, "
        "seed and generator hash are recorded in summary.json. These are invented phone-use rhythms, not real "
        "people or evidence of emergency detection. All device channels are simulated; movement is unknown. "
        "This is the primary base for behaviour scenarios 1–6 and also supports observation scenarios 7–10 "
        "after pre-injection review.\n", encoding="utf-8")
    write_json(out / "SHA256.json", {p.name: sha256(p) for p in sorted(out.iterdir()) if p.is_file() and p.name != "SHA256.json"})
    write_json(version_root() / "review_gate.json", {"state": "waiting_for_pre_injection_review", "injection_allowed": False})
    return summary
